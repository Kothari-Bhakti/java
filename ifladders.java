
package bhakti;

public class ifladders {
    public static void main(String[] args) {
        //if else ladders
        
        int  i =20; // initialization i=20
        if(i==10)// 20==10
        {
            System.out.println("i is 10");
        }
        else if(i ==20) // 20==20
        {
            System.out.println("i is 20");
        }
        else if(i ==30)//20==30
        {
             System.out.println("i is 30");
        }
        else if(i ==40)//20==40
        {
            System.out.println("i is 40");
        }
        else
        {
            System.out.println("there are no any matching number.....");
            // output " not any matching value"
        }
            
            
    }
    
}
